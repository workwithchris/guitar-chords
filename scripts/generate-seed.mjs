const OUT_PATH = path.resolve(__dirname, '..', OUTPUT)

let insert = `-- Migration: Seed ~1000 English & Nepali songs
-- Generated: ${new Date().toISOString()}

BEGIN;

`

function escapeVal(v) {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'number') return String(v)
  if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE'
  const s = String(v).replace(/'/g, "''")
  return `'${s}'`
}

// Artists
insert += `-- Artists\n`
insert += `INSERT INTO artist (name, slug, bio, "isActive") VALUES\n`

const allArtists = { ...engArtists, ...nepaliArtists }
const artistNames = Object.keys(allArtists)
const artistRows = artistNames.map((slug) => {
  const a = allArtists[slug]
  return `  (${escapeVal(a.name)}, ${escapeVal(slug)}, ${escapeVal(a.bio || null)}, TRUE)`
})
insert += artistRows.join(',\n') + '\n'
insert += `ON CONFLICT (slug) DO NOTHING;\n\n`

// Songs
insert += `-- Songs\n`
let totalSongs = 0

for (const [slug, artist] of Object.entries(allArtists)) {
  for (const [title, difficulty, genre, key, year] of artist.songs) {
    const songSlug = toSlug(title) + '-' + slug
    const cnt = content(title, artist.name, key)

    insert += `INSERT INTO song (title, slug, "artistId", difficulty, genre, key, year, content, "isActive")\n`
    insert += `VALUES (${escapeVal(title)}, ${escapeVal(songSlug)}, (SELECT id FROM artist WHERE slug = ${escapeVal(slug)}),\n`
    insert += `  ${escapeVal(difficulty)}, ${escapeVal(genre)}, ${escapeVal(key)}, ${escapeVal(year)},\n`
    insert += `  $song_content$${cnt}$song_content$,\n`
    insert += `  TRUE)\n`
    insert += `ON CONFLICT (slug) DO NOTHING;\n`
    totalSongs++
  }
}

insert += `\nCOMMIT;\n`

